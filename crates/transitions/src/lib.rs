//! Переходы «Диджей» — общая часть сервера и аудиодвижка приложений.
//!
//! - [`analysis`] — анализ трека для сведения (сетка долей, фразы по 8 тактов, вокал, энергия) и
//!   предложенные точки сведения. Сервер считает фразы и точки тем же кодом, что и движок.
//! - [`plan`] — выбор перехода для пары треков: где уходящий уступает место (граница фразы после
//!   вокала), с какой сильной доли входит следующий, какой приём и сколько тактов.
//! - [`curves`] — автоматика перехода во времени: громкости, эквалайзер, фильтры, эхо. Без
//!   выделения памяти — её считает микшер прямо в аудиоколбэке.
//! - [`tempo`] — карта темпа входящего трека: растяжение до темпа уходящего и плавный возврат к своему.
//! - [`key`] — совместимость тональностей по кругу Камелота.
//! - [`set`] — «Собрать как сет»: порядок треков плейлиста по тональности, темпу и кривой энергии.
//!
//! Все времена — миллисекунды `f64`: в треке (позиция в файле) или от начала перехода.

pub mod analysis;
pub mod curves;
pub mod key;
pub mod plan;
pub mod set;
pub mod tempo;

