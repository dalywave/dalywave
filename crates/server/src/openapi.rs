pub struct ApiDoc;

struct Security;

impl Modify for Security {
    fn modify(&self, openapi: &mut utoipa::openapi::OpenApi) {
        // Лицензии у личного проекта нет: пустое поле из Cargo.toml только сбивает генераторы
        openapi.info.license = None;
        let components = openapi.components.get_or_insert_with(Default::default);
        components.add_security_scheme(
            "session",
            SecurityScheme::ApiKey(ApiKey::Cookie(ApiKeyValue::with_description(
                crate::session::SESSION_COOKIE,
                "Сессия сайта (HttpOnly cookie)",
            ))),
        );
        components.add_security_scheme(
            "device",
            SecurityScheme::Http(
                HttpBuilder::new()
                    .scheme(HttpAuthScheme::Bearer)
                    .description(Some("Токен приложения `dwd_…`"))
                    .build(),
            ),
        );
        components.add_security_scheme(
            "jam",
            SecurityScheme::Http(
                HttpBuilder::new()
                    .scheme(HttpAuthScheme::Bearer)
                    .description(Some(
                        "Токен гостя «Слушать вместе» `dwj_…`: только `/api/jam/guest/*` своей сессии",
                    ))
                    .build(),
            ),
        );
        components.add_security_scheme(
            "downloader",
            SecurityScheme::Http(
                HttpBuilder::new()
                    .scheme(HttpAuthScheme::Bearer)
                    .description(Some(
                        "Токен домашнего загрузчика `dwk_…`: только `/api/fetcher/*`",
                    ))
                    .build(),
            ),
        );
        components.add_security_scheme(
            "release",
            SecurityScheme::Http(
                HttpBuilder::new()
                    .scheme(HttpAuthScheme::Bearer)
                    .description(Some(
                        "Токен конвейера выпусков `DALYWAVE_RELEASE_TOKEN`: только `/api/releases*`",
                    ))
                    .build(),
            ),
        );
    }
}
