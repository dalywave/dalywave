//! Загрузки на устройство.
//!
//! [`plan`] решает, что держать и что качать в пределах места: закреплённое человеком — первым, затем
//! умный запас (набор волны) в его порядке, затем кэш (скачанное, которое больше не закреплено и не в
//! запасе) — пока помещается. Вытесняется в обратном порядке: сначала кэш (давно не игравшее первым),
//! затем хвост запаса; закреплённое само не удаляется никогда — что не поместилось, просто не качается.
//!
//! [`fetch`] качает один файл: в `.part` рядом с итоговым, с места обрыва (`Range`), проверяет размер и
//! SHA-256 и только тогда переименовывает. На iPhone сами байты качает фоновая сессия URLSession
//! (оболочка), а проверка и учёт — те же ([`verify`]).

mod fetch;
mod plan;

pub use fetch::{FetchError, Request, fetch, part_path, verify};
pub use plan::{Plan, PlanInput, plan};

/// Размер трека, пока сервер не сказал точный: ~4,5 МБ у Opus 130–160 кбит/с, с запасом.
pub const ESTIMATED_TRACK_BYTES: u64 = 6 * 1024 * 1024;
/// После стольких неудач подряд трек больше не качается сам (до следующего закрепления или «Повторить»).
pub const MAX_ATTEMPTS: u32 = 5;
